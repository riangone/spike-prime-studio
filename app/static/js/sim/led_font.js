/**
 * Official LEGO SPIKE 3 5x5 Light Matrix built-in images (IDs 1..67) and 5x5 ASCII bitmap font.
 * Keeps official SPIKE 3 integer IDs so expressions like `light_matrix.IMAGE_HEART + i`
 * cycle through real distinct icons, identical to the physical Hub.
 */

function parseGrid(rows) {
  const out = new Array(25).fill(0);
  for (let r = 0; r < 5; r++) {
    const line = rows[r] || '.....';
    for (let c = 0; c < 5; c++) {
      const ch = line[c];
      if (ch === '#' || ch === '9') out[r * 5 + c] = 100;
      else if (ch >= '1' && ch <= '8') out[r * 5 + c] = Math.round((Number(ch) / 9) * 100);
    }
  }
  return out;
}

