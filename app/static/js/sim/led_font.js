export const IMAGE_CONSTANTS = {};
export const IMAGE_PIXELS = {};
export const IMAGE_NAMES = {};

IMAGE_DEFS.forEach(([name, rows], idx) => {
  const id = idx + 1;
  IMAGE_CONSTANTS[name] = id;
  IMAGE_PIXELS[id] = parseGrid(rows);
  IMAGE_NAMES[id] = name.replace(/^IMAGE_/, '');
});

export function getImagePixels(imageId) {
  if (typeof imageId === 'string' && IMAGE_CONSTANTS[imageId] !== undefined) {
    return IMAGE_PIXELS[IMAGE_CONSTANTS[imageId]].slice();
  }
  const n = Math.trunc(Number(imageId) || 0);
  if (n <= 0) return new Array(25).fill(0);
  const count = IMAGE_DEFS.length;
  const wrapped = ((n - 1) % count + count) % count + 1;
  return IMAGE_PIXELS[wrapped].slice();
}

