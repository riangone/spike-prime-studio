/**
 * Render a string into an array of 5-row columns (each column is an array of 5 values in 0..intensity)
 * suitable for horizontal scrolling across the 5x5 LED matrix.
 */
export function textToColumns(text, intensity = 100) {
  const s = String(text ?? '').toUpperCase();
  const cols = [];
  // Leading blank padding so text scrolls smoothly into view
  for (let i = 0; i < 4; i++) cols.push([0, 0, 0, 0, 0]);
  for (const ch of s) {
    const glyph = FONT_RAW[ch] || FONT_RAW[' '];
    const width = glyph[0].length;
    for (let c = 0; c < width; c++) {
      const col = [0, 0, 0, 0, 0];
      for (let r = 0; r < 5; r++) {
        col[r] = glyph[r][c] === '#' ? intensity : 0;
      }
      cols.push(col);
    }
    cols.push([0, 0, 0, 0, 0]); // 1-column inter-character spacing
  }
  for (let i = 0; i < 4; i++) cols.push([0, 0, 0, 0, 0]);
  return cols;
}

export function sliceWindow(cols, offset) {
  const grid = new Array(25).fill(0);
  for (let c = 0; c < 5; c++) {
    const col = cols[offset + c];
    if (!col) continue;
    for (let r = 0; r < 5; r++) grid[r * 5 + c] = col[r];
  }
  return grid;
}
