"""Export a lesson's block program as a Scratch 3 project (.sb3).

Purpose: students who learn with Scratch first can open the same program in scratch.mit.edu,
read/edit the script without knowing Blockly, and see how the word blocks map to SPIKE 3 Python.

How the SPIKE word blocks are drawn in pure Scratch:
  * a small "SPIKE 3D Studio" extension (id `s3studio`) supplies one generic block,
    `runFunction(function, inputs)`, for motor / light / sound / sensor commands. Its arguments use
    the same vocabulary as the SPIKE 3 Python API: motor.run_for_degrees(port.A, 360, 500).
  * Scratch variables `A … F` hold the port constants (port.A == "A"), so port choices are real
    Scratch variables a teacher can change;
  * control flow (repeat / forever / if / repeat until / wait until) and operators are native
    Scratch blocks; the lesson's variables become native Scratch variables.
Every SPIKE block carries a Scratch comment naming the Python call it stands for, and the first
script carries a comment explaining the whole mapping.

Runtime note: the extension is declared, not implemented. scratch.mit.edu loads the project and
keeps the blocks, but the green block does nothing there — that is intentional, it keeps the block
*names readable under any language preference*. The flashable program is the generated SPIKE 3
Python (.py / .llsp3).
"""
