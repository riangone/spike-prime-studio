def build_sb3(lesson: Dict[str, Any], lang: str, var_defs: Dict[str, Any], sprite_name: str = "SPIKE Hub") -> bytes:
    """Assemble a .sb3 project for the lesson. `var_defs` maps Scratch variable name -> initial value,
    including the port constants A…F ("A" == "A") that the SPIKE blocks reference."""
    port_ids = {p: _next_id("var") for p in PORTS}
    var_ids_base = dict(port_ids)  # ports are Scratch variables too: port.A == "A"
    # Every variable the blocks touch must exist, even if the caller forgot to pre-declare it.
    names = [n for n in var_defs if n not in PORTS] + [n for n in bx.parse_var_names(lesson.get("blocks", "")) if n not in PORTS and n not in var_defs]
    var_ids = {name: _next_id("var") for name in dict.fromkeys(names)}
    var_ids_all = {**var_ids_base, **var_ids}
    script = build_script(lesson, lang, var_ids_all, port_ids)

    variables: Dict[str, List[Any]] = {vid: [p, p] for p, vid in port_ids.items()}
    for name, vid in var_ids.items():
        variables[vid] = [name, var_defs.get(name, 0)]

    project = {
        "targets": [
            _stage_target(variables),
            {
                "isStage": False,
                "name": sprite_name,
                "variables": {},
                "lists": {},
                "broadcasts": {},
                "blocks": script["blocks"],
                "comments": script["comments"],
                "currentCostume": 0,
                "costumes": [_costume()],
                "sounds": [],
                "volume": 100,
                "layerOrder": 1,
                "visible": True,
                "x": 0,
                "y": 0,
                "size": 100,
                "direction": 90,
                "draggable": False,
                "rotationStyle": "all around",
            },
        ],
        "monitors": [],
        "extensions": [BLOCKLIB_ID],
        "meta": {"semver": "3.0.0", "vm": "0.2.0", "agent": "SPIKE Prime 3D Studio"},
    }

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("project.json", json.dumps(project, ensure_ascii=False))
        zf.writestr(_BLANK_MD5 + ".png", _BLANK_PNG)
    return buf.getvalue()


