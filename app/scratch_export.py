def _link(blocks: Dict[str, Any], ids: List[str]) -> None:
    if not ids:
        return
    blocks[ids[0]]["parent"] = blocks[ids[0]].get("parent")
    for a, b in zip(ids, ids[1:]):
        blocks[a]["next"] = b
        blocks[b]["parent"] = a


def _join(ctx: Ctx, slots: List[List[Any]]) -> str:
    """Left-nested operator_join over the template slots; pure-text neighbours are folded."""
    chunks: List[List[Any]] = []
    pending = ""
    for s in slots:
        if s[0] == 1 and s[1][0] == 10:
            pending += str(s[1][1])
        else:
            if pending:
                chunks.append(Ctx.literal_text(pending))
                pending = ""
            chunks.append(s)
    if pending or not chunks:
        chunks.append(Ctx.literal_text(pending))

    def build(i: int) -> str:
        left = chunks[i]
        if i == len(chunks) - 1:
            return ctx.add("operator_join", {"STRING1": left, "STRING2": Ctx.literal_text("")})
        right = build(i + 1)
        return ctx.add("operator_join", {"STRING1": left, "STRING2": [3, right, [10, ""]]})

    return build(0)


def build_script(lesson: Dict[str, Any], lang: str, var_ids: Dict[str, str], port_ids: Dict[str, str]) -> Dict[str, Any]:
    """Translate the lesson's `<script id="lesson-blocks-xml">` program into a Scratch script.

    Returns {"blocks": {...}, "comments": {...}} for the sprite.
    """
    ctx = Ctx(lang, var_ids, port_ids, {})
    roots = bx.parse_blocks(lesson.get("blocks", ""))
    extra_tops: List[str] = []
    for root in roots:
        if root["type"] != "spike_start":
            for n in _chain(root):
                sid = ctx.statement(n)
                if sid:
                    extra_tops.append(sid)
            continue
        hat = ctx.hat()
        nodes = list(_chain(root))
        if not nodes:  # an empty hat still waits one tick so the flag works predictably
            nodes = [_wait_node(0.01)]
        ids = [i for i in (ctx.statement(n) for n in nodes) if i]
        if ids:
            _link(ctx.blocks, ids)
            ctx.blocks[hat]["next"] = ids[0]
            ctx.blocks[ids[0]]["parent"] = hat
    for i, sid in enumerate(extra_tops):
        ctx.blocks[sid].update({"topLevel": True, "x": 24, "y": 220 + 40 * i})
    _fix_parents(ctx.blocks)
    return {"blocks": ctx.blocks, "comments": ctx.comments}


def _fix_parents(blocks: Dict[str, Any]) -> None:
    for bid, b in blocks.items():
        for inp in b.get("inputs", {}).values():
            if isinstance(inp, list) and len(inp) >= 2 and isinstance(inp[1], str) and inp[1] in blocks:
                blocks[inp[1]]["parent"] = bid
        if b.get("next") in blocks:
            blocks[b["next"]]["parent"] = bid


