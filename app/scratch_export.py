def messages(lang: str) -> Dict[str, Any]:
    return SPIKE_MSG.get(lang, SPIKE_MSG["zh"])


def _num(text: Any) -> Any:
    try:
        fv = float(text)
    except (TypeError, ValueError):
        return text
    return int(fv) if fv.is_integer() else fv


_SEQ = [0]


def _next_id(prefix: str) -> str:
    _SEQ[0] += 1
    return f"{prefix}{_SEQ[0]:05d}"


class Ctx:
    """State for translating one lesson's Blockly XML into Scratch blocks."""

    def __init__(self, lang: str, var_ids: Dict[str, str], port_ids: Dict[str, str], comments: Dict[str, str]):
        self.msg = messages(lang)
        self.labels: Dict[str, List[str]] = self.msg["labels"]
        self.vars = var_ids
        self.ports = port_ids
        self.comments = comments
        self.blocks: Dict[str, Any] = {}
        self.unsupported: set[str] = set()

    # ------------------------------------------------------------ block factories
    def add(self, opcode: str, inputs: Optional[Dict[str, Any]] = None, fields: Optional[Dict[str, Any]] = None) -> str:
        bid = _next_id("b")
        self.blocks[bid] = {
            "opcode": opcode,
            "next": None,
            "parent": None,
            "inputs": inputs or {},
            "fields": fields or {},
            "shadow": False,
            "topLevel": False,
        }
        return bid

    def hat(self) -> str:
        bid = self.add("event_whenflagclicked")
        b = self.blocks[bid]
        b.update({"topLevel": True, "x": 24, "y": 24})
        cid = _next_id("c")
        self.comments[cid] = {"blockId": bid, "x": 380, "y": 24, "width": 340, "height": 190,
                              "minimized": False, "text": self.msg["intro"]}
        return bid

    # ------------------------------------------------------------ inputs
    @staticmethod
    def literal_number(v: Any) -> List[Any]:
        return [1, [4, _num(v)]]

    @staticmethod
    def literal_text(v: Any) -> List[Any]:
        return [1, [10, str(v)]]

    def value(self, node: Optional[Dict[str, Any]]) -> List[Any]:
        """A value input slot: inline literal or inline reporter."""
        if node is None:
            return self.literal_number(0)
        if node["type"] == "math_number":
            return self.literal_number(node["fields"].get("NUM", "0"))
        if node["type"] == "text":
            return self.literal_text(node["fields"].get("TEXT", ""))
        rid = self.reporter(node)
        if isinstance(rid, str):
            return [3, rid, [10, ""]]
        return self.literal_number(0)

    def port(self, port: str) -> List[Any]:
        return self.var_reporter(port)

    def var_reporter(self, name: str, bid: Optional[str] = None) -> List[Any]:
        """Inline `data_variable` reporter for a Scratch variable (ports and lesson variables alike)."""
        rid = bid or self.add("data_variable", fields={"VARIABLE": [name, self.vars[name]]})
        return [3, rid, [10, ""]]

    @staticmethod
    def label_key(block_type: str) -> str:
        """`spike_motor_run_for` -> `motor_run_for` (the key used in SPIKE_MSG[...]["labels"])."""
        return block_type[len("spike_"):] if block_type.startswith("spike_") else block_type

    # ------------------------------------------------------------ reporters
    def reporter(self, node: Dict[str, Any]) -> Optional[str]:
        t = node["type"]
        f = node.get("fields", {})
        v = node.get("values", {})
        if t == "variables_get":
            return self.var_reporter(f["VAR"])[1]
        if t == "math_arithmetic":
            op = {"ADD": "operator_add", "MINUS": "operator_subtract", "MULTIPLY": "operator_multiply",
                  "DIVIDE": "operator_divide"}.get(f.get("OP"), "operator_add")
            return self.add(op, {"NUM1": self.value(v.get("A")), "NUM2": self.value(v.get("B"))})
        if t == "logic_compare":
            cmp_op = f.get("OP")
            if cmp_op in ("EQ", "NEQ"):
                return self.add("operator_equals", {"OPERAND1": self.value(v.get("A")), "OPERAND2": self.value(v.get("B"))})
            # Scratch has no ≤ / ≥ / ≠; use not(<) / not(>) to keep the boolean exact.
            inner = "operator_lt" if cmp_op in ("LTE", "LT") else "operator_gt"
            bid = self.add(inner, {"OPERAND1": self.value(v.get("A")), "OPERAND2": self.value(v.get("B"))})
            if cmp_op in ("LTE", "GTE"):
                bid = self.add("operator_not", {"OPERAND": [3, bid, [10, ""]]})
            return bid
        if t == "logic_operation":
            op = "operator_and" if f.get("OP") == "AND" else "operator_or"
            return self.add(op, {"OPERAND1": self.value(v.get("A")), "OPERAND2": self.value(v.get("B"))})
        if t == "logic_negate":
            return self.add("operator_not", {"OPERAND": self.value(v.get("BOOL"))})
        if t == "spike_abs":
            return self.add("operator_mathop", {"NUM": self.value(v.get("NUM"))}, {"OPERATOR": ["abs"]})
        if t == "spike_yaw":  # tenths of a degree in Python; no native Scratch block takes it
            # `‹yaw sensor›` (a marked placeholder) so learners can at least rebuild the formula.
            return self.add("operator_round", {"NUM": [3, self.hint_join("yaw sensor")[1], [4, 0]]})
        if t == "spike_getvar":
            return self.var_reporter(f["NAME"])[1]
        if t == "spike_button_pressed":  # the official Scratch block is `button ▾ pressed?`
            return self.spike("button_pressed", node)
        key = self.label_key(t)
        if key in self.labels:
            return self.spike(key, node)
        return None

    def hint_join(self, text: str, extra: Optional[str] = None) -> List[Any]:
        """Inline `‹text›` reporter used where Scratch has no native block (marked, never silent)."""
        rid = self.add("operator_join", {"STRING1": self.literal_text(f"<{text}"),
                                         "STRING2": self.literal_text(">" if not extra else f" {extra}>")})
        return [3, rid, [10, ""]]

    # ------------------------------------------------------------ statements
    def statement(self, node: Dict[str, Any]) -> Optional[str]:
        t = node["type"]
        f = node.get("fields", {})
        v = node.get("values", {})
        st = node.get("statements", {})
        if t == "spike_setvar":  # Scratch-flavour "set variable to"
            return self.add("data_setvariableto", {"VALUE": self.value(v.get("VALUE"))},
                            {"VARIABLE": [f["NAME"], self.vars[f["NAME"]]]})
        if t == "variables_set":  # Blockly core "set variable to"
            return self.add("data_setvariableto", {"VALUE": self.value(v.get("VALUE"))},
                            {"VARIABLE": [f["VAR"], self.vars[f["VAR"]]]})
        if t == "math_change":
            return self.add("data_changevariableby", {"VALUE": self.value(v.get("DELTA"))},
                            {"VARIABLE": [f["VAR"], self.vars[f["VAR"]]]})
        if t == "spike_wait":
            return self.add("control_wait", {"DURATION": self.value(v.get("SECS"))})
        if t == "spike_repeat":
            return self.substack("control_repeat", {"TIMES": self.value(v.get("TIMES"))}, st.get("DO", []))
        if t == "spike_forever":
            return self.substack("control_forever", {}, st.get("DO", []))
        if t == "spike_repeat_until":
            return self.substack("control_repeat_until", {"CONDITION": self.value(v.get("COND"))}, st.get("DO", []))
        if t == "spike_wait_until":
            # `wait until c` == `repeat until c { wait 0.01 s }`, keep the loop yielding like runloop.sleep_ms.
            return self.substack("control_repeat_until", {"CONDITION": self.value(v.get("COND"))}, [_wait_node(0.01)],
                                 slot="SUBSTACK")
        if t == "spike_if":
            return self.substack("control_if", {"CONDITION": self.value(v.get("COND"))}, st.get("DO", []))
        if t == "spike_if_else":
            bid = self.substack("control_if_else", {"CONDITION": self.value(v.get("COND"))}, st.get("DO", []))
            self.substack_into(bid, "SUBSTACK2", st.get("ELSE", []))
            return bid
        if t == "spike_print":
            return self.add(PRINT_ID, {"VALUE": self.value(v.get("VALUE"))})
        key = self.label_key(t)
        if key in self.labels:
            return self.spike(key, node)
        # Unknown block: skipped rather than crashing the export, but said so on the script.
        self.comments[_next_id("c")] = {"blockId": None, "x": 380, "y": 230, "width": 300, "height": 80,
                                        "minimized": False,
                                        "text": f"⚠ {t}\n{self.msg['unsupported']}"}
        self.unsupported.add(t)
        return None

    def substack(self, opcode: str, inputs: Dict[str, Any], body: List[Dict[str, Any]], slot: str = "SUBSTACK") -> str:
        bid = self.add(opcode, dict(inputs))
        self.substack_into(bid, slot, body)
        return bid

    def substack_into(self, parent: str, slot: str, body: List[Dict[str, Any]]) -> None:
        ids = [i for i in (self.statement(n) for n in body) if i]
        if not ids:
            return
        _link(self.blocks, ids)
        self.blocks[parent]["inputs"][slot] = [2, ids[0]]

    # ------------------------------------------------------------ SPIKE extension block
    def spike(self, function: str, node: Dict[str, Any]) -> str:
        """One green `runFunction` block for a motor/light/sound/sensor word block."""
        template = self.labels.get(function, [""])
        f = node.get("fields", {})
        v = node.get("values", {})
        slots: List[List[Any]] = []
        ports_used: List[str] = []
        for piece in template:
            slot = self.template_slot(piece, f, v)
            if slot is None:
                continue
            slots.append(slot)
            if piece == "{PORT}":
                ports_used.append(f.get("PORT", "A"))
        for key, value in v.items():  # inputs the template forgot stay visible, never silent
            if not any(piece == "{" + key + "}" for piece in template):
                slots.extend([self.literal_text(f" {key}="), self.value(value)])
        joined = _join(self, slots)
        bid = self.add(FUNC_RUN, {"function": self.literal_text(function), "inputs": [3, joined, [10, ""]]})
        python = PYTHON_CALLS.get(function)
        if python:
            self.comments[_next_id("c")] = {
                "blockId": bid, "x": 24, "y": 0, "width": 250, "height": 60, "minimized": True,
                "text": python.format(port=ports_used[0] if ports_used else "?"),
            }
        return bid

    def template_slot(self, piece: str, f: Dict[str, str], v: Dict[str, Any]) -> Optional[List[Any]]:
        if not (piece.startswith("{") and piece.endswith("}") and len(piece) > 2):
            return self.literal_text(piece)
        key = piece[1:-1]
        if key == "PORT":
            return self.port(f.get("PORT", "A"))
        if key in v:
            return self.value(v[key])
        if key in f:
            return self.literal_text(f[key])
        return self.literal_text("")


def _chain(root: Dict[str, Any]):
    """Yield a root block and everything linked after it (the parser keeps <next> nested)."""
    node: Optional[Dict[str, Any]] = root
    while node is not None:
        yield node
        node = node.get("next")


def _wait_node(secs: float) -> Dict[str, Any]:
    return {"type": "spike_wait", "fields": {}, "statements": {},
            "values": {"SECS": {"type": "math_number", "fields": {"NUM": str(secs)}, "values": {}, "statements": {}}}}


