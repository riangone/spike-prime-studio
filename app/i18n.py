def normalize_lang(lang: str | None) -> str:
    if lang and lang in SUPPORTED_LANGS:
        return lang
    return DEFAULT_LANG


def get_ui(lang: str) -> Dict[str, str]:
    return UI_STRINGS.get(normalize_lang(lang), UI_STRINGS[DEFAULT_LANG])


def pick_i18n(value: Any, lang: str) -> Any:
    if isinstance(value, dict) and any(k in value for k in SUPPORTED_LANGS):
        return value.get(lang) or value.get(DEFAULT_LANG) or next(iter(value.values()))
    return value
